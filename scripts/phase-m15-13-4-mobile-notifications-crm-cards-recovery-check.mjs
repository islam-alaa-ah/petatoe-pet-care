import fs from 'node:fs';
const read = p => fs.readFileSync(p,'utf8');
const checks = [];
const expect = (name, ok) => checks.push([name, !!ok]);
const notif = read('assets/js/notification-center.js');
const mobile = read('assets/css/mobile.css');
const version = JSON.parse(read('version.json'));
expect('pointerup bell handler', notif.includes("bell?.addEventListener('pointerup'") && notif.includes("e.pointerType==='mouse'"));
expect('bell click duplicate guard', notif.includes('Date.now()-lastPointerToggle<700'));
expect('customer card two-column mobile', mobile.includes('#customersView tbody tr {\n    display: grid !important;\n    grid-template-columns: repeat(2, minmax(0, 1fr)) !important;'));
expect('customer name full width', mobile.includes('td[data-mobile-field="name"] {\n    order: 1 !important;\n    grid-column: 1 / -1 !important;'));
expect('customer actions full width', mobile.includes('td[data-mobile-field="actions"] {\n    order: 10 !important;\n    grid-column: 1 / -1 !important;'));
expect('followups header vertical collapse recovery', mobile.includes('#followupsView > .actions-row {\n    display: flex !important;\n    flex-direction: column !important;'));
expect('followups horizontal writing', mobile.includes('writing-mode: horizontal-tb !important;'));
expect('followups export grid', mobile.includes('#followupsView > .actions-row .report-export-actions {') && mobile.includes('grid-template-columns: repeat(2, minmax(0, 1fr)) !important;'));
expect('version', version.version === '18.53.31' && version.build === 185331);
const failed = checks.filter(([,ok])=>!ok);
for (const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`);
if (failed.length) process.exit(1);
console.log(`RESULT ${checks.length}/${checks.length} PASS`);
