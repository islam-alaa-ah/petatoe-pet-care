const aggregate = row('2','cash_aggregate','صادرة',230,200,30);
const cancelled = row('3','invoice','ملغاة',46,40,6);
let s = summarize([issued,aggregate]);
assert.equal(s.total,345,'revenue must include aggregate');
assert.equal(s.invoiceCount,1,'aggregate is not a customer invoice');
assert.equal(s.averageInvoice,115,'average excludes cash aggregate');
assert.equal(s.tax,45);
s = summarize([cancelled]);
assert.equal(s.invoiceCount,1,'cancelled filter keeps its invoice details');
assert.equal(s.total,46);
s = summarize([issued,aggregate,cancelled]);
assert.equal(s.invoiceCount,2);
assert.equal(s.total,391);
assert.equal(s.issuedShare, 2/3*100);
assert.equal(filterRows.call(null,{year:2026,month:10,vehicle:'',customer:'',team:'',payment:'',status:'ملغاة'}).length,0); // zero allRows in isolated context
