const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const js = fs.readFileSync(path.join(__dirname, '../assets/js/sales-reports.js'),'utf8');
const exposed = js.replace(/\}\)\(\);\s*$/, '\nwindow.__A2_TEST__ = { summarize, filterRows, normalizeRow, aggregateInvoiceRows };\n})();');
assert.notEqual(exposed, js, 'test access hook was not installed');
const context = {window: {addEventListener(){}}, document: {addEventListener(){}}, navigator: {}, Intl, Date, Map, Set, Number, String, Math, console};
vm.runInNewContext(exposed, context);
const {summarize, filterRows, normalizeRow} = context.window.__A2_TEST__;
const row = (id, record_type, status, total, before, tax, date='2026-10-05') => normalizeRow({row_id:id, record_type, status, amount_incl_tax:total, amount_before_tax:before, tax_amount:tax, invoice_date:date,invoice_number:id, customer_id:'c1'});
