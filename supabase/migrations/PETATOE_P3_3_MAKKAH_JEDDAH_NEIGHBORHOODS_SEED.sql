select
  r.name as region_name,
  c.name as city_name,
  count(n.id)::bigint as neighborhood_count
from public.installation_regions r
join public.installation_cities c on c.region_id=r.id
left join public.installation_neighborhoods n
  on n.region_id=r.id
 and n.city_id=c.id
 and n.is_active=true
where r.name='منطقة مكة المكرمة'
  and c.name='جدة'
group by r.name,c.name;

select n.name,n.city,n.region,n.is_active
from public.installation_neighborhoods n
join public.installation_cities c on c.id=n.city_id
join public.installation_regions r on r.id=n.region_id
where r.name='منطقة مكة المكرمة'
  and c.name='جدة'
order by n.name;
